//! 扫描 workspace 能力目录，生成 Provider 注册表。

use std::fs;
use std::path::Path;

use ability_support::{RuntimeKind, resolve_runtime_kind};

const EXCLUDE: &[&str] = &[
    "devkit",
    "codegen_fixture",
    "test_feedback",
    // Guest 合规夹具，仅测试安装
    "ability-probe-ts",
    "ability-probe-py",
    "ability-probe-surface-ts",
    "ability-probe-surface-py",
];

struct ScanEntry {
    id: String,
    rel: String,
    feature: String,
    rust_crate: Option<String>,
    kind: RuntimeKind,
}

fn main() {
    let manifest_dir_str = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let manifest_dir = Path::new(&manifest_dir_str);
    let workspace = manifest_dir
        .join("../..")
        .canonicalize()
        .unwrap_or_else(|_| manifest_dir.join("../.."));
    let out_dir_str = std::env::var("OUT_DIR").unwrap();
    let out_dir = Path::new(&out_dir_str);
    let generated_path = out_dir.join("providers.rs");

    let mut entries: Vec<ScanEntry> = Vec::new();
    scan_ability_dir(&workspace.join("abilitys"), "abilitys", &mut entries);
    let apps_dir = workspace.join("apps");
    if let Ok(apps) = fs::read_dir(&apps_dir) {
        for app_entry in apps.flatten() {
            let app_path = app_entry.path();
            let Some(app) = app_path.file_name().and_then(|s| s.to_str()) else {
                continue;
            };
            let rel_parent = format!("apps/{app}/ability");
            scan_ability_dir(&app_path.join("ability"), &rel_parent, &mut entries);
        }
    }
    scan_ability_dir(&workspace.join("external"), "external", &mut entries);

    entries.sort_by(|a, b| a.id.cmp(&b.id));

    let mut code = String::from("// @generated by build.rs\n\n");
    code.push_str("use std::sync::Arc;\n");
    code.push_str("use ability_core::{AbilityHost, GuestSourceProvider};\n");
    code.push_str("use crate::catalog::workspace_root;\n\n");

    code.push_str("/// 安装全部已链接 Provider。\n");
    code.push_str("pub async fn install_all(host: &AbilityHost) {\n");
    for e in &entries {
        code.push_str(&format!("    #[cfg(feature = \"{}\")]\n", e.feature));
        match e.kind {
            RuntimeKind::Rust => {
                let mod_name = e
                    .rust_crate
                    .as_deref()
                    .unwrap_or(&e.feature)
                    .replace('-', "_");
                code.push_str(&format!(
                    "    if let Err(err) = host.install_str(\"{}\", {}::provider()).await {{\n        tracing::warn!(id = \"{}\", error = %err, \"install ability 失败\");\n    }}\n",
                    e.id, mod_name, e.id
                ));
            }
            RuntimeKind::Node | RuntimeKind::Python | RuntimeKind::Cangjie => {
                code.push_str(&format!(
                    "    if let Err(err) = host.install_str(\"{}\", GuestSourceProvider::from_workspace_rel(&workspace_root(), \"{}\").into_provider()).await {{\n        tracing::warn!(id = \"{}\", error = %err, \"install guest ability 失败\");\n    }}\n",
                    e.id, e.rel, e.id
                ));
            }
        }
    }
    code.push_str("}\n\n");

    code.push_str("/// 当前二进制已链接的 source id。\n");
    code.push_str("pub fn linked_ids() -> Vec<&'static str> {\n    let mut v = Vec::new();\n");
    for e in &entries {
        code.push_str(&format!(
            "    #[cfg(feature = \"{}\")]\n    v.push(\"{}\");\n",
            e.feature, e.id
        ));
    }
    code.push_str("    v\n}\n\n");

    code.push_str("/// 编译期 source 元数据（id → 相对根路径）。\n");
    code.push_str("pub fn compiled_sources() -> Vec<(&'static str, &'static str)> {\n    vec![\n");
    for e in &entries {
        code.push_str(&format!("        (\"{}\", \"{}\"),\n", e.id, e.rel));
    }
    code.push_str("    ]\n}\n");

    fs::write(&generated_path, code).unwrap();
    println!("cargo:rerun-if-changed={}", apps_dir.display());
    println!(
        "cargo:rerun-if-changed={}",
        workspace.join("abilitys").display()
    );
    println!(
        "cargo:rerun-if-changed={}",
        workspace.join("external").display()
    );
}

fn scan_ability_dir(ability_dir: &Path, rel_parent: &str, entries: &mut Vec<ScanEntry>) {
    if !ability_dir.is_dir() {
        return;
    }
    println!("cargo:rerun-if-changed={}", ability_dir.display());
    let Ok(read) = fs::read_dir(ability_dir) else {
        return;
    };
    for entry in read.flatten() {
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        let folder = path.file_name().and_then(|s| s.to_str()).unwrap_or("");
        let rel = format!("{rel_parent}/{folder}");
        let yml_path = path.join("ability.yml");
        if !yml_path.is_file() {
            scan_ability_dir(&path, &rel, entries);
            continue;
        }
        if EXCLUDE.contains(&folder) {
            continue;
        }
        println!("cargo:rerun-if-changed={}", yml_path.display());
        let yml = fs::read_to_string(&yml_path).unwrap_or_default();
        let id = parse_yaml_id(&yml).unwrap_or_else(|| folder.replace('_', "."));
        let kind = parse_runtime_kind(&yml, &path);
        let (feature, rust_crate) = match kind {
            RuntimeKind::Rust => {
                let toml_path = path.join("Cargo.toml");
                if !toml_path.is_file() {
                    continue;
                }
                let pkg =
                    parse_package_name(&toml_path).unwrap_or_else(|| folder.replace('_', "-"));
                (feature_name(&pkg), Some(pkg))
            }
            RuntimeKind::Node | RuntimeKind::Python | RuntimeKind::Cangjie => {
                (folder.replace('_', "-"), None)
            }
        };
        entries.push(ScanEntry {
            id,
            rel,
            feature,
            rust_crate,
            kind,
        });
    }
}

fn parse_yaml_id(yml: &str) -> Option<String> {
    let doc: serde_yaml::Value = serde_yaml::from_str(yml).ok()?;
    doc.get("id")?.as_str().map(|s| s.to_string())
}

fn parse_runtime_kind(yml: &str, root: &Path) -> RuntimeKind {
    let doc: serde_yaml::Value = serde_yaml::from_str(yml).unwrap_or(serde_yaml::Value::Null);
    let fw = doc
        .get("framework_version")
        .and_then(|v| v.as_str())
        .unwrap_or("1");
    resolve_runtime_kind(root, fw).unwrap_or(RuntimeKind::Rust)
}

fn parse_package_name(toml_path: &Path) -> Option<String> {
    let raw = fs::read_to_string(toml_path).ok()?;
    for line in raw.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix("name = ") {
            return Some(rest.trim().trim_matches('"').to_string());
        }
    }
    None
}

fn feature_name(pkg: &str) -> String {
    match pkg {
        "ai-dispatch" => "ability-dispatch".into(),
        "ai-chat" => "ability-chat".into(),
        "ai-turn" => "ability-turn".into(),
        "ai-skill" => "ability-skill".into(),
        "ai-prompt" => "ability-prompt".into(),
        "ai-session" => "ability-session".into(),
        other => other.to_string(),
    }
}
